import pg from 'pg'

const { Pool } = pg

const toPostgresSql = (sql) => {
  let parameter = 0
  return sql.replace(/\?/g, () => `$${++parameter}`)
}

export const createPostgresUserStore = ({ connectionString }) => {
  const pool = new Pool({ connectionString })

  const importSnapshot = async (snapshot) => {
    const client = await pool.connect()
    try {
      await client.query('BEGIN')
      await client.query('SELECT pg_advisory_xact_lock(7351931)')
      const existingUsers = await client.query('SELECT COUNT(*) AS total FROM users')
      if (Number(existingUsers.rows[0].total) > 0) {
        await client.query('COMMIT')
        return false
      }

      for (const user of snapshot.users) {
        await client.query(
          `INSERT INTO users
             (id, first_name, last_name, email, country, city, address, password, created_at)
           VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
           ON CONFLICT (id) DO NOTHING`,
          [
            user.id,
            user.first_name,
            user.last_name,
            user.email,
            user.country,
            user.city,
            user.address,
            user.password,
            user.created_at,
          ]
        )
      }
      for (const license of snapshot.licenses) {
        await client.query(
          `INSERT INTO ea_licenses
             (id, user_id, broker_name, broker_server, account_login,
              account_type, status, created_at, approved_at)
           VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
           ON CONFLICT (id) DO NOTHING`,
          [
            license.id,
            license.user_id,
            license.broker_name,
            license.broker_server,
            license.account_login,
            license.account_type,
            license.status,
            license.created_at,
            license.approved_at,
          ]
        )
      }
      await client.query(`
        SELECT setval(
          pg_get_serial_sequence('users', 'id'),
          COALESCE((SELECT MAX(id) FROM users), 1),
          EXISTS (SELECT 1 FROM users)
        )
      `)
      await client.query(`
        SELECT setval(
          pg_get_serial_sequence('ea_licenses', 'id'),
          COALESCE((SELECT MAX(id) FROM ea_licenses), 1),
          EXISTS (SELECT 1 FROM ea_licenses)
        )
      `)
      await client.query('COMMIT')
      return true
    } catch (error) {
      await client.query('ROLLBACK')
      throw error
    } finally {
      client.release()
    }
  }

  return {
    pool,

    async init(legacyDb, all) {
      await pool.query(`
        CREATE TABLE IF NOT EXISTS users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          first_name TEXT NOT NULL DEFAULT '',
          last_name TEXT NOT NULL DEFAULT '',
          email TEXT NOT NULL UNIQUE,
          country TEXT NOT NULL DEFAULT '',
          city TEXT NOT NULL DEFAULT '',
          address TEXT NOT NULL DEFAULT '',
          password TEXT NOT NULL,
          created_at TEXT NOT NULL DEFAULT TO_CHAR(
            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
            'YYYY-MM-DD HH24:MI:SS'
          )
        )
      `)
      await pool.query(`
        CREATE TABLE IF NOT EXISTS ea_licenses (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id BIGINT NOT NULL REFERENCES users(id),
          broker_name TEXT NOT NULL,
          broker_server TEXT NOT NULL,
          account_login TEXT NOT NULL,
          account_type TEXT NOT NULL CHECK (account_type IN ('demo', 'real')),
          status TEXT NOT NULL CHECK (status IN ('pending', 'active', 'rejected')),
          created_at TEXT NOT NULL DEFAULT TO_CHAR(
            CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
            'YYYY-MM-DD HH24:MI:SS'
          ),
          approved_at TEXT
        )
      `)
      await pool.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS ea_licenses_account_unique
        ON ea_licenses(account_login, LOWER(broker_server))
      `)

      const existingUsers = await pool.query('SELECT COUNT(*) AS total FROM users')
      if (Number(existingUsers.rows[0].total) > 0) return

      const legacyUsers = await all(
        legacyDb,
        `SELECT id, first_name, last_name, email, country, city, address, password, created_at
         FROM users ORDER BY id`
      )
      const legacyLicenses = await all(
        legacyDb,
        `SELECT id, user_id, broker_name, broker_server, account_login,
                account_type, status, created_at, approved_at
         FROM ea_licenses ORDER BY id`
      )
      if (legacyUsers.length === 0) return

      const imported = await importSnapshot({ users: legacyUsers, licenses: legacyLicenses })
      if (imported) {
        console.info(
          `Imported ${legacyUsers.length} legacy accounts and ${legacyLicenses.length} EA licenses into PostgreSQL.`
        )
      }
    },

    run(database, sql, params = []) {
      const query = toPostgresSql(sql)
      const shouldReturnId = /^\s*INSERT\s+INTO\s+(users|ea_licenses)\b/i.test(sql)
      const withReturning = shouldReturnId && !/\bRETURNING\b/i.test(query)
        ? `${query} RETURNING id`
        : query
      return pool.query(withReturning, params).then((result) => ({
        lastID: result.rows[0]?.id,
        changes: result.rowCount,
      }))
    },

    get(_database, sql, params = []) {
      return pool.query(toPostgresSql(sql), params).then((result) => result.rows[0])
    },

    all(_database, sql, params = []) {
      return pool.query(toPostgresSql(sql), params).then((result) => result.rows)
    },

    importSnapshot,

    close() {
      return pool.end()
    },
  }
}
